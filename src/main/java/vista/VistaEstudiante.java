    private void botonCalcularActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_botonCalcularActionPerformed
        // TODO add your handling code here:
        try{
            //capturar datos
            String nombre = inputNombre.getText().trim();
            double nota1 = Double.parseDouble(inputDesarrollo.getText());
            double nota2 = Double.parseDouble(inputMatematicas.getText());
            //conectar con modelo estudiante
            Estudiante miEstudiante = new Estudiante(nombre, nota1, nota2);

            //que lo coloque en la interfaz
            String mensaje = String.format("Estudiante : %s | Definitiva: %.2f (%s)", 
                    miEstudiante.getNombre(), 
                    miEstudiante.calcularDefinitiva(), 
                    miEstudiante.obtenerEstado());
            lblResultado.setText(mensaje);        
        } catch(NumberFormatException e ){
            JOptionPane.showMessageDialog(this, "Por favor ingresa valores numericos validos en las notas.", "Error de formato", JOptionPane.ERROR_MESSAGE);
        
        }
    }//GEN-LAST:event_botonCalcularActionPerformed

